/**
 * Writes src/lib/studyapp/library/ipadSeats.ts: the iPad's Grand Library seats, in the iPad's order, so a seat
 * number heard from an iPad (`ls` in the realtime "move") means the same chair here.
 *
 *   npm run library:seats                regenerate (needs the app repo beside this one, or APP_REPO=/path)
 *   npm run library:seats -- --check     fail if the committed file is not what the app's lib_world.json gives
 *
 * The iPad's `LibraryWorld` (Sources/PlumiKit/Features/StudyTime/Library/LibraryWorld.swift, init) takes
 * `seats` from lib_world.json in file order, then APPENDS the one glass study pod upstairs, which is the first
 * of the file's `spots` with a crop at x > 1000 and y < 400. That is index 75, the last one. This file does
 * the same, so the numbers agree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const app = process.env.APP_REPO ?? resolve(__dirname, "../../plumi");
const world = JSON.parse(readFileSync(resolve(app, "Sources/PlumiKit/Resources/Library/lib_world.json"), "utf8")) as {
  w: number; h: number;
  seats: { x: number; y: number; view: string; t: string }[];
  spots: { x: number; y: number; crop?: number[] | null }[];
};
const seats = world.seats.map((s) => [s.x, s.y, s.view, s.t] as const);
const pod = world.spots.find((s) => s.crop && s.x > 1000 && s.y < 400);
if (pod) seats.push([pod.x, pod.y, "back", "pod"]);

const body = `// GENERATED by scripts/library-seats.ts from the app repo's Resources/Library/lib_world.json. Do not edit by hand.
// The iPad's Grand Library seats in the iPad's order (the order \`ls\` counts in): [x, y, view, table], in ROOM POINTS
// (the iPad's room is ${world.w} x ${world.h}; this site's is half that). The last is the study pod upstairs.
export const IPAD_ROOM = { w: ${world.w}, h: ${world.h} } as const;
export const IPAD_SEATS: readonly (readonly [x: number, y: number, view: string, table: string])[] = [
${seats.map((s) => `  [${s[0]}, ${s[1]}, ${JSON.stringify(s[2])}, ${JSON.stringify(s[3])}],`).join("\n")}
];
`;
const out = resolve(__dirname, "../src/lib/studyapp/library/ipadSeats.ts");
if (process.argv.includes("--check")) {
  let have = "";
  try { have = readFileSync(out, "utf8"); } catch { /* missing */ }
  if (have !== body) { console.error("ipadSeats.ts is not what the app's lib_world.json gives: run npm run library:seats"); process.exit(1); }
  console.log(`ipadSeats.ts matches lib_world.json (${seats.length} seats).`);
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out}: ${seats.length} seats`);
}
