/**
 * Writes src/app/study/tokens.css from src/components/study/tokens.ts.
 *
 *   npm run study:tokens           regenerate
 *   npm run study:tokens -- --check  fail if the committed file is not what the source produces
 *
 * The CSS is generated so the TypeScript (which the contrast check reads) and the stylesheet
 * (which the browser reads) are one thing, not two things that agree today.
 *
 * Selectors: the app root `.st` follows the page's own `data-theme` / `data-look` on <html>
 * (set before first paint). `.st-scope` is the same palette keyed by its own attributes,
 * so a style guide can draw all four palettes side by side.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { constantsCss, paletteCss, palettes, paperStocks } from "../src/components/study/tokens";

const out = resolve(__dirname, "../src/app/study/tokens.css");

const stocks = paperStocks
  .map((s) => `.st-paper[data-stock="${s.id}"] { --pg: ${s.page}; --pg-rule: ${s.rule}; --pg-ink: ${s.ink}; --pg-tutor: ${s.tutor}; --pg-wrong: ${s.wrong}; }`)
  .join("\n");

const css = `/* GENERATED by scripts/study-tokens.ts from src/components/study/tokens.ts. Do not edit by hand:
   change the TypeScript, run \`npm run study:tokens\`. \`--check\` fails CI if this file has drifted. */

/* Mode-independent tokens, and the default palette: blue, light. */
.st, .st-scope {
${constantsCss()}
${paletteCss(palettes.blue.light, "light")}
}

/* lime, light */
html[data-look="lime"] .st,
.st-scope[data-look="lime"] {
${paletteCss(palettes.lime.light, "light")}
}

/* blue, dark */
html[data-theme="dark"] .st,
.st-scope[data-mode="dark"] {
${paletteCss(palettes.blue.dark, "dark")}
}

/* lime, dark */
html[data-theme="dark"][data-look="lime"] .st,
.st-scope[data-mode="dark"][data-look="lime"] {
${paletteCss(palettes.lime.dark, "dark")}
}

/* Writing paper keeps its own stock in every look and mode. */
${stocks}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* missing counts as drift */ }
  if (current !== css) {
    console.error("src/app/study/tokens.css is out of date. Run: npm run study:tokens");
    process.exit(1);
  }
  console.log("tokens.css matches tokens.ts");

  // Every var(--st-*) the study app uses must be defined somewhere. An undefined variable
  // silently invalidates the whole declaration (a padding of 0, a missing border), which is
  // how a typo shipped once already.
  const root = resolve(__dirname, "..");
  const files: string[] = [];
  const walk = (dir: string) => {
    for (const name of readdirSync(dir)) {
      const full = resolve(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (/\.(css|tsx?)$/.test(name)) files.push(full);
    }
  };
  walk(resolve(root, "src/app/study"));
  walk(resolve(root, "src/components/study"));
  const defined = new Set<string>();
  const used = new Map<string, string>();
  for (const f of files) {
    const text = readFileSync(f, "utf8");
    for (const m of text.matchAll(/(--st-[a-z0-9-]+)\s*:/g)) defined.add(m[1]);
    for (const m of text.matchAll(/\["(--st-[a-z0-9-]+)"/g)) defined.add(m[1]);
    for (const m of text.matchAll(/var\((--st-[a-z0-9-]+)/g)) used.set(m[1], f.replace(root + "/", ""));
  }
  const undefinedVars = [...used].filter(([v]) => !defined.has(v));
  if (undefinedVars.length) {
    for (const [v, f] of undefinedVars) console.error(`undefined token ${v} used in ${f}`);
    process.exit(1);
  }
  console.log(`all ${used.size} token references resolve`);
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out}`);
}
