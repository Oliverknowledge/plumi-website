/**
 * Writes supabase/checks/social_applied.sql: one read-only query to paste into the Supabase SQL editor
 * (or run with `npm run social:contract`), answering "does this project have what the website's multiplayer
 * needs?" One row per thing, `ok` or `MISSING`. It is generated from the same RPC and READS tables the
 * code is written against (src/lib/social/api.ts), so the check and the code cannot disagree.
 *
 *   npm run social:check-sql             regenerate
 *   npm run social:check-sql -- --check  fail if the committed file is not what the source gives
 *
 * It changes nothing: it reads the catalogue only.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { READS, RPC } from "../src/lib/social/api";

const out = resolve(__dirname, "../supabase/checks/social_applied.sql");

/** What each app migration adds that the website leans on: a sentinel that is present only once it ran. */
const MIGRATIONS: { m: string; what: string; test: string }[] = [
  { m: "0104", what: "friends and groups (social_profile, friendship, study_group, group_member, study_presence, social_summary)", test: "to_regclass('public.social_profile') IS NOT NULL AND to_regclass('public.friendship') IS NOT NULL AND to_regclass('public.study_group') IS NOT NULL AND to_regclass('public.group_member') IS NOT NULL AND to_regclass('public.study_presence') IS NOT NULL AND to_regclass('public.social_summary') IS NOT NULL" },
  { m: "0105", what: "anonymous users are refused by every social call (social_caller)", test: "EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'ai_usage_today')" },
  { m: "0107", what: "study hall: emblems, goals, reactions", test: "EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='study_group' AND column_name='hall_theme') AND to_regclass('public.group_reaction') IS NOT NULL" },
  { m: "0108", what: "avatars (social_profile.avatar, set_avatar)", test: "EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='social_profile' AND column_name='avatar')" },
  { m: "0109", what: "group chat with moderation (group_message, chat_refusal)", test: "to_regclass('public.group_message') IS NOT NULL AND to_regclass('public.chat_banned_term') IS NOT NULL" },
  { m: "0110", what: "hall positions (hall_position)", test: "to_regclass('public.hall_position') IS NOT NULL" },
  { m: "0112", what: "friends' streaks (social_summary.streak)", test: "EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='social_summary' AND column_name='streak')" },
  { m: "0113", what: "the hall and chat in real time (private channel policies)", test: "to_regclass('realtime.messages') IS NOT NULL AND EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='realtime' AND tablename='messages' AND policyname='plumi_realtime_receive') AND EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='realtime' AND tablename='messages' AND policyname='plumi_realtime_send')" },
  // study_group.visibility has existed since 0104 (with one allowed value), so the column proves nothing; the join request function does.
  { m: "0118", what: "public groups and asking to join one (request_to_join)", test: "EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.proname = 'request_to_join')" },
];

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: readonly string[]) => (a.length ? `ARRAY[${a.map(q).join(", ")}]::text[]` : "ARRAY[]::text[]");

const rpcRows = Object.entries(RPC).map(([key, spec]) => `    (${q(key)}, ${q(spec.name)}, ${arr([...spec.args].sort())})`).join(",\n");
// Every ladder for a table, so the check can say how far up the ladder this server is.
const ladders = new Map<string, string[]>();
for (const r of Object.values(READS)) ladders.set(r.table, [...new Set([...(ladders.get(r.table) ?? []), ...r.ladder])]);
const tableRowsAll = [...ladders.entries()].map(([t, l]) => `    (${q(t)}, ARRAY[${l.map(q).join(", ")}]::text[])`).join(",\n");

const sql = `-- GENERATED by scripts/social-check-sql.ts from src/lib/social/api.ts. Do not edit by hand:
-- change api.ts, run \`npm run social:check-sql\`.
--
-- Does this Supabase project have what the website's multiplayer needs? Paste all of this into the SQL
-- editor and Run. It only reads the catalogue; it changes nothing. Every row says ok or MISSING.
--
--   migration   an app migration (Supabase/migrations/NNNN in the app repo) the website leans on
--   rpc         a function the website calls, with exactly those argument names, callable when signed in
--               and NOT by a signed-out visitor (the browser key is public, so this matters)
--   table       a table the website reads: row-level security on, signed-in students may select,
--               a signed-out visitor may not
--   columns     how far up the website's column ladder this server goes (1 = the newest; the website
--               still works from any rung, but newer features need the first)
--   realtime    private-channel policies on realtime.messages (the hall's steps and the chat's pings)
--
-- Anything MISSING under "migration" is a file to run in the SQL editor, in number order, from the app
-- repo's Supabase/migrations. Also turn OFF Realtime > Settings > "Allow public access" (a dashboard
-- setting, so this cannot check it): a channel can then only be joined through the policies above.

WITH
migrations(m, what, ok) AS (VALUES
${MIGRATIONS.map((x) => `    (${q(x.m)}, ${q(x.what)}, (${x.test}))`).join(",\n")}
),
want_rpc(key, fn, args) AS (VALUES
${rpcRows}
),
have AS (
  SELECT p.proname AS fn, p.oid,
         (SELECT coalesce(array_agg(nm ORDER BY nm), ARRAY[]::text[])
            FROM (SELECT replace(split_part(trim(a), ' ', 1), '"', '') AS nm
                    FROM unnest(CASE WHEN pg_get_function_identity_arguments(p.oid) = '' THEN ARRAY[]::text[]
                                     ELSE string_to_array(pg_get_function_identity_arguments(p.oid), ', ') END) a) t) AS args
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public'
),
want_table(tbl, ladder) AS (VALUES
${tableRowsAll}
),
column_step AS (
  SELECT w.tbl,
         (SELECT min(i) FROM generate_subscripts(w.ladder, 1) i
           WHERE NOT EXISTS (SELECT 1 FROM unnest(string_to_array(w.ladder[i], ',')) c
                              WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns k
                                                 WHERE k.table_schema = 'public' AND k.table_name = w.tbl AND k.column_name = c))) AS step,
         cardinality(w.ladder) AS steps
    FROM want_table w
)
SELECT area, what, CASE WHEN ok THEN 'ok' ELSE 'MISSING' END AS status, note FROM (
  SELECT 1 AS o, 'migration' AS area, m || ': ' || what AS what, ok, '' AS note FROM migrations
  UNION ALL
  SELECT 2, 'rpc', w.fn || '(' || array_to_string(w.args, ', ') || ')',
         EXISTS (SELECT 1 FROM have h WHERE h.fn = w.fn AND h.args = w.args AND has_function_privilege('authenticated', h.oid, 'EXECUTE') AND NOT has_function_privilege('anon', h.oid, 'EXECUTE')),
         CASE WHEN NOT EXISTS (SELECT 1 FROM have h WHERE h.fn = w.fn) THEN 'no such function'
              WHEN EXISTS (SELECT 1 FROM have h WHERE h.fn = w.fn AND has_function_privilege('anon', h.oid, 'EXECUTE')) THEN 'SIGNED-OUT VISITORS CAN CALL THIS' ELSE '' END
    FROM want_rpc w
  UNION ALL
  SELECT 3, 'table', w.tbl,
         to_regclass('public.' || w.tbl) IS NOT NULL
           AND coalesce((SELECT c.relrowsecurity FROM pg_class c WHERE c.oid = to_regclass('public.' || w.tbl)), false)
           AND coalesce(has_table_privilege('authenticated', to_regclass('public.' || w.tbl), 'SELECT'), false)
           AND NOT coalesce(has_table_privilege('anon', to_regclass('public.' || w.tbl), 'SELECT'), false),
         CASE WHEN to_regclass('public.' || w.tbl) IS NULL THEN 'no such table'
              WHEN coalesce(has_table_privilege('anon', to_regclass('public.' || w.tbl), 'SELECT'), false) THEN 'SIGNED-OUT VISITORS CAN READ THIS' ELSE '' END
    FROM want_table w
  UNION ALL
  SELECT 4, 'columns', s.tbl, s.step IS NOT NULL,
         CASE WHEN s.step IS NULL THEN 'not even the oldest set' ELSE 'rung ' || s.step || ' of ' || s.steps END
    FROM column_step s
  UNION ALL
  SELECT 5, 'realtime', 'private channel policies on realtime.messages',
         to_regclass('realtime.messages') IS NOT NULL
           AND EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'realtime' AND tablename = 'messages' AND policyname IN ('plumi_realtime_receive', 'plumi_realtime_send')),
         CASE WHEN to_regclass('realtime.messages') IS NULL THEN 'Realtime is not on this project' ELSE '' END
) r
ORDER BY o, what;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* missing counts as drift */ }
  if (current !== sql) { console.error("supabase/checks/social_applied.sql is out of date. Run: npm run social:check-sql"); process.exit(1); }
  console.log("social_applied.sql matches api.ts");
} else {
  writeFileSync(out, sql);
  console.log(`wrote ${out}`);
}
